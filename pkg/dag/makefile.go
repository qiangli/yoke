// Agents reach for `make` first. `--makefile` meets them there: it projects
// the dag into a generated, forward-only POSIX Makefile (like --skill
// projects it into an Agent Skill) whose header teaches the native form.
// The Makefile carries no logic and no dag dependency edges: every recipe
// is `bashy dag <target>`, so ordering, up-to-date skipping and effect caps
// stay in dag. It must run under both GNU make and the coreutils POSIX
// make, so it uses no GNU-only syntax — notably no .PHONY, which the
// coreutils make rejects. The FORCE prerequisite (a rule naming no file,
// with no recipe) is the portable substitute: it keeps a forward running
// when a file or directory on disk shares the target's name.

// makefileMarker is written into every generated Makefile; a re-run
// overwrites a file that carries it and refuses to clobber one that does not.
const makefileMarker = "bashy dag --makefile"

// makefileBanner opens the generated file. A Makefile has no bold, so the
// frame does that job. Measured in runes every line is 75 wide (the em dash
// is one rune, three bytes).
const makefileBanner = "###########################################################################\n" +
	"##  GENERATED FILE — DO NOT EDIT.                                        ##\n" +
	"##  Produced from dag.md by `bashy dag --makefile`. Edit dag.md instead, ##\n" +
	"##  then regenerate; manual changes are overwritten and fail --check.    ##\n" +
	"###########################################################################\n"

const makefileHeader = "# Tasks live in dag.md (a bashy dag file); this Makefile only forwards.\n" +
	"#   bashy dag <target>           run a target (its dependencies first)\n" +
	"#   bashy dag --list             list targets\n" +
	"#   bashy dag --dry-run <target> print the plan, run nothing\n" +
	"#   bashy dag --skill DIR        export these tasks as an Agent Skill\n" +
	"# Regenerate with: bashy dag --makefile  (verify: bashy dag --makefile --check)\n"

// makefileGuard prefixes every recipe: without bashy on PATH the forward
// cannot run, so say where to get it instead of a bare "not found".
const makefileGuard = `command -v bashy >/dev/null || { echo "requires bashy: https://github.com/qiangli/bashy"; exit 127; }`

type makefileResult struct {
	File     string `json:"file"`
	Makefile string `json:"makefile"`
	Targets  int    `json:"targets"`
	UpToDate bool   `json:"up_to_date,omitempty"`
}

func runMakefile(out, errOut io.Writer, mode weavecli.OutputMode, doc *Document, outPath string, check bool) error {
	body := renderMakefile(doc, makefileBaseCmd(doc.Path, outPath))
	res := makefileResult{File: doc.Path, Makefile: outPath, Targets: len(doc.Order)}
	regen := "bashy dag --makefile"
	if outPath != "Makefile" {
		regen += " -o " + outPath
	}
	if check {
		old, err := os.ReadFile(outPath)
		if err != nil {
			return emitErr(errOut, mode, errf(weavecli.ExitGenericFail,
				"--makefile --check: cannot read %s: %v; regenerate with `%s`", outPath, err, regen))
		}
		if !bytes.Equal(old, body) {
			return emitErr(errOut, mode, errf(weavecli.ExitGenericFail,
				"--makefile --check: %s is stale; regenerate with `%s`", outPath, regen))
		}
		res.UpToDate = true
		if mode == weavecli.OutputJSON {
			emitOK(out, res)
			return nil
		}
		fmt.Fprintf(out, "ok: %s is up to date\n", outPath)
		return nil
	}
	if old, err := os.ReadFile(outPath); err == nil && !bytes.Contains(old, []byte(makefileMarker)) {
		return emitErr(errOut, mode, errf(weavecli.ExitInvalidArg,
			"--makefile: %s exists and was not generated by %s; refusing to overwrite", outPath, makefileMarker))
	}
	if dir := filepath.Dir(outPath); dir != "." && dir != "" {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return emitErr(errOut, mode, errf(weavecli.ExitGenericFail, "--makefile: %v", err))
		}
	}
	tmp := outPath + ".tmp"
	if err := os.WriteFile(tmp, body, 0o644); err != nil {
		return emitErr(errOut, mode, errf(weavecli.ExitGenericFail, "--makefile: %v", err))
	}
	if err := os.Rename(tmp, outPath); err != nil {
		os.Remove(tmp)
		return emitErr(errOut, mode, errf(weavecli.ExitGenericFail, "--makefile: %v", err))
	}
	if mode == weavecli.OutputJSON {
		emitOK(out, res)
		return nil
	}
	fmt.Fprintf(out, "makefile: %s\n", outPath)
	return nil
}

// makefileBaseCmd is how the generated recipes invoke dag: plain
// "bashy dag" when the dag file sits beside the Makefile (make runs there
// and discovery finds it), otherwise "bashy dag -f <path>" with the path
// relative to the Makefile's directory, so a generated file never carries
// a host path.
func makefileBaseCmd(dagPath, outPath string) string {
	absDag, err := filepath.Abs(dagPath)
	if err != nil {
		return "bashy dag"
	}
	absOut, err := filepath.Abs(outPath)
	if err != nil {
		return "bashy dag"
	}
	outDir := filepath.Dir(absOut)
	if filepath.Dir(absDag) == outDir {
		return "bashy dag"
	}
	rel, err := filepath.Rel(outDir, absDag)
	if err != nil || strings.HasPrefix(rel, "..") {
		rel = filepath.Base(absDag)
	}
	return "bashy dag -f " + filepath.ToSlash(rel)
}

// renderMakefile renders the generated Makefile: banner, teaching header,
// a help rule first (bare `make` runs the first rule in both makes), one
// forward per dag target in declaration order, .DEFAULT for unknown
// targets, and the empty FORCE rule. A dag target named "help" replaces
// the fixed help rule but stays first.
func renderMakefile(doc *Document, base string) []byte {
	var b bytes.Buffer
	b.WriteString(makefileBanner)
	b.WriteString(makefileHeader)
	b.WriteString("\n")

	_, hasHelp := doc.Lookup("help")
	_, hasForce := doc.Lookup("FORCE")
	rule := func(name, desc, recipe string) {
		if d := firstSentence(desc); d != "" {
			fmt.Fprintf(&b, "# %s\n", d)
		}
		if name == "FORCE" {
			// The sentinel itself cannot require itself.
			b.WriteString("FORCE:\n")
		} else {
			fmt.Fprintf(&b, "%s: FORCE\n", name)
		}
		fmt.Fprintf(&b, "\t@%s; %s\n\n", makefileGuard, recipe)
	}
	if !hasHelp {
		rule("help", "List the dag targets, then how to run them natively.",
			base+" --list; echo \"Run: bashy dag <target> | skill: bashy dag --skill DIR | more: bashy help\"")
	}
	names := make([]string, 0, len(doc.Order))
	if hasHelp {
		names = append(names, "help")
	}
	for _, n := range doc.Order {
		if n != "help" {
			names = append(names, n)
		}
	}
	for _, n := range names {
		t, _ := doc.Lookup(n)
		rule(n, t.Desc, base+" "+n)
	}
	// .DEFAULT must not carry prerequisites (POSIX), so FORCE stops here:
	// an unknown target reaches dag, whose error lists the targets.
	fmt.Fprintf(&b, ".DEFAULT: ; @%s; %s $@\n", makefileGuard, base)
	if !hasForce {
		b.WriteString("\n# FORCE names no file and has no recipe: as the one prerequisite it\n" +
			"# keeps every forward running even when a file or directory on disk\n" +
			"# shares a target's name. Dependency order stays in dag, not here.\n" +
			"FORCE:\n")
	}
	return b.Bytes()
}
